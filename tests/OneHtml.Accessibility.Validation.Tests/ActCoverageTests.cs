namespace RecursiveAI.OneHtml.Accessibility.Validation.Tests;

/// <summary>
/// Publishes <c>docs/act-coverage.md</c>: every ACT rule, whether a rule of the package implements it, and how its
/// vendored cases came out in the per-area ACT tests. The test fails when an approved or proposed rule is neither
/// implemented nor given a reason, so the table cannot drift from the code. Refresh the file with <c>ONEHTML_UPDATE_DOCS=1</c>.
/// </summary>
public sealed partial class ActCoverageTests
{
    /// <summary>Rules no rule of the package implements, and why (the ones in structure are added from <see cref="StructureActTests.NotImplemented"/>).</summary>
    private static readonly (string Act, string Reason)[] s_notAutomatable =
    [
        ("36b590", "the error indicators of a form field (wording, icons, colour, position) are presentation with no markup that names them, so no element set can be offered for review"),
        ("59br37", "it needs the text laid out at 200% zoom to see whether an overflow clips it; there is no layout without a browser"),
        ("7677a9", "it depends on what a script does with device-motion events; scripts are inert text here"),
        ("c249d5", "it depends on what a script does with device-motion events; scripts are inert text here"),
        ("80af7b", "it depends on running focus and key handlers; a keyboard trap is made by script"),
        ("a1b64e", "it depends on running focus and key handlers; a keyboard trap is made by script"),
        ("ebe86a", "it depends on running focus and key handlers; a keyboard trap is made by script"),
        ("9bd38c", "it asks whether instructions rely only on shape, size, position or colour; that is a judgement about the wording of the content, with no element to point at"),
        ("efbfc7", "it depends on timing, scripts and animation to know that text changes by itself"),
        ("ffbc54", "it depends on the key handlers a script installs"),
        ("in6db8", "deprecated by the ACT task force; the check lives on in aria-valid-attr-value (6a7281)"),
        ("9eb3f6", "deprecated by the ACT task force; a file name is not an accessible name"),
    ];

    internal static readonly string[] Header =
    [
        "# ACT rule coverage",
        "",
        "Generated by `ActCoverageTests`; do not edit by hand. To refresh it after a rule or an expectation changes, run the",
        "Validation tests with `ONEHTML_UPDATE_DOCS=1`. The rule list and its status come from `Catalogue/Data/act-rules.json`",
        "(see `catalogue.md`); the cases are the W3C test cases vendored under `testdata/act/`.",
        "",
        "Columns: *Our rules* are the rules of this package that take the ACT rule as a source (or that the ACT harness runs",
        "for it). The case columns count the vendored cases of the rule: *pass* the rule gave the expected outcome, *review*",
        "the rule asks a person (needs-review) where ACT expects passed or failed, which is the honest answer for a judgement",
        "rule, *n/a* cases a static check cannot judge (each is listed with its reason in the `testdata/act/*-expectations.tsv`",
        "files), and *fail* cases where the rule disagrees with ACT. *Fail* is 0 everywhere; ACT wins disagreements.",
        "",
    ];

    private sealed record Row(string Rules, int Pass, int Review, int Na, int Fail, string? Reason);

    [GeneratedRegex(@"(pass|judgement|n/a|fail) (\d+)")]
    private static partial Regex CountPattern();

    private static Dictionary<string, Row> Collect(List<string> problems)
    {
        var rows = new Dictionary<string, Row>(StringComparer.Ordinal);
        var evaluations = new[]
        {
            AriaActTests.Evaluate(), NamesActTests.Evaluate(), StructureActTests.Evaluate(),
            TablesFormsLanguageActTests.Evaluate(), VisualActTests.Evaluate(), ActGapActTests.Evaluate(),
        };
        foreach ((string text, List<string> p) in evaluations)
        {
            problems.AddRange(p);
            foreach (string line in text.Split('\n', StringSplitOptions.RemoveEmptyEntries))
            {
                string[] f = line.TrimEnd('\r').Split('\t');
                if (f.Length < 3 || f[1] == "not a rule")
                {
                    continue;
                }

                int pass = 0, review = 0, na = 0, fail = 0;
                foreach (Match m in CountPattern().Matches(line))
                {
                    int n = int.Parse(m.Groups[2].Value, System.Globalization.CultureInfo.InvariantCulture);
                    switch (m.Groups[1].Value)
                    {
                        case "pass": pass = n; break;
                        case "judgement": review = n; break;
                        case "n/a": na = n; break;
                        default: fail = n; break;
                    }
                }

                string rules = f[1].StartsWith("pass ", StringComparison.Ordinal) ? string.Empty : f[1];
                rows[f[0]] = new Row(rules, pass, review, na, fail, null);
            }
        }

        return rows;
    }

    internal static string Document(List<string> problems)
    {
        Dictionary<string, Row> rows = Collect(problems);
        var reasons = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach ((string act, string reason) in StructureActTests.NotImplemented)
        {
            reasons[act] = reason;
        }

        foreach ((string act, string reason) in s_notAutomatable)
        {
            reasons[act] = reason;
        }

        var implementing = new Dictionary<string, SortedSet<string>>(StringComparer.Ordinal);
        foreach (IAccessibilityRule rule in BuiltInRules.All)
        {
            foreach (RuleSource s in rule.Descriptor.Sources.Where(s => s.Kind == RuleSourceKind.Act))
            {
                if (!implementing.TryGetValue(s.Id, out SortedSet<string>? set))
                {
                    implementing[s.Id] = set = new SortedSet<string>(StringComparer.Ordinal);
                }

                set.Add(rule.Descriptor.Id);
            }
        }

        IReadOnlyList<ActTestCase> cases = ActTestCases.Parse(File.ReadAllText(Path.Combine(AriaActTests.Repo, "testdata", "act", "testcases.json")));
        var table = new StringBuilder();
        table.AppendLine("| ACT id | Name | Status | Our rules | Cases | pass | review | n/a | fail |");
        table.AppendLine("|---|---|---|---|---|---|---|---|---|");
        var tally = new Dictionary<ActRuleStatus, (int Total, int Implemented)>();
        foreach (ActRule rule in ActRules.All.OrderBy(r => r.Status).ThenBy(r => r.Id, StringComparer.Ordinal))
        {
            implementing.TryGetValue(rule.Id, out SortedSet<string>? mine);
            var names = new SortedSet<string>(mine ?? [], StringComparer.Ordinal);
            if (rows.TryGetValue(rule.Id, out Row? row))
            {
                foreach (string r in row.Rules.Split(',', StringSplitOptions.RemoveEmptyEntries))
                {
                    names.Add(r);
                }
            }

            int caseCount = cases.Count(c => c.RuleId == rule.Id);
            string ours;
            if (names.Count > 0)
            {
                ours = string.Join(", ", names.Select(n => "`" + n + "`"));
            }
            else if (reasons.TryGetValue(rule.Id, out string? reason))
            {
                ours = (rule.Status == ActRuleStatus.Deprecated ? "not implemented \u2014 " : "not automatable \u2014 ") + reason;
            }
            else
            {
                ours = "not implemented";
                if (rule.Status != ActRuleStatus.Deprecated)
                {
                    problems.Add(rule.Id + " " + rule.Name + " is neither implemented nor explained");
                }
            }

            (int total, int impl) = tally.GetValueOrDefault(rule.Status);
            tally[rule.Status] = (total + 1, impl + (names.Count > 0 ? 1 : 0));
            string counts = row is null
                ? (caseCount == 0 ? "| 0 | | | | |" : "| " + caseCount + " | | | | |")
                : "| " + caseCount + " | " + row.Pass + " | " + row.Review + " | " + row.Na + " | " + row.Fail + " |";
            table.AppendLine("| " + rule.Id + " | " + rule.Name + " | " + rule.Status.ToString().ToLowerInvariant() + " | " + ours + " " + counts);
            if (row is not null && row.Pass + row.Review + row.Na + row.Fail != caseCount)
            {
                problems.Add(rule.Id + ": the harness counted " + (row.Pass + row.Review + row.Na + row.Fail) + " of " + caseCount + " cases");
            }

            if (row is { Fail: > 0 })
            {
                problems.Add(rule.Id + " has failing cases");
            }

            if (rule.Status == ActRuleStatus.Approved && names.Count == 0 && !reasons.ContainsKey(rule.Id))
            {
                problems.Add(rule.Id + " is approved and has no rule and no reason");
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine(string.Join("\n", Header));
        foreach (ActRuleStatus s in new[] { ActRuleStatus.Approved, ActRuleStatus.Proposed, ActRuleStatus.Deprecated })
        {
            (int total, int impl) = tally.GetValueOrDefault(s);
            sb.AppendLine("- " + s + ": " + total + " rules, " + impl + " implemented" + (total - impl > 0 ? ", " + (total - impl) + " not automatable or not implemented (reason in the table)" : "") + ".");
        }

        sb.AppendLine();
        sb.Append(table);
        return sb.ToString();
    }

    [Fact]
    public void Act_coverage_document_is_current()
    {
        var problems = new List<string>();
        string expected = Document(problems);
        string path = Path.Combine(AriaActTests.Repo, "docs", "act-coverage.md");
        if (Environment.GetEnvironmentVariable("ONEHTML_UPDATE_DOCS") == "1")
        {
            File.WriteAllText(path, expected);
        }

        Assert.True(problems.Count == 0, string.Join("\n", problems));
        Assert.Equal(expected, File.ReadAllText(path));
    }
}
