#!/usr/bin/env python3
"""Generates the named-colour table of RecursiveAI.OneHtml from CSS Color Module Level 4.

Input: the specification HTML, https://drafts.csswg.org/css-color-4/ (Editor's Draft; its SHA-256 and the
retrieval date given on the command line are written into the generated file).

Usage: tools/generate-css-colors.py <css-color-4.html> <retrieval date>

Output: src/OneHtml/Css/Generated/NamedColors.g.cs
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    path, date = sys.argv[1], sys.argv[2]
    raw = open(path, "rb").read()
    text = raw.decode("utf-8", errors="ignore")
    rows = re.findall(r'valdef-color-([a-z]+)">\1</dfn>\s*<td>#([0-9a-f]{6})', text)
    if len(rows) != 148:
        sys.exit("expected 148 named colours, found %d" % len(rows))
    rows.sort()
    body = "\n".join('        ("%s", 0x%s),' % (n, h.upper()) for n, h in rows)
    out = """// <auto-generated>
// Generated by tools/generate-css-colors.py. Do not edit.
// Source: CSS Color Module Level 4, section "Named Colors", https://drafts.csswg.org/css-color-4/
// retrieved %s, SHA-256 of the retrieved HTML %s.
// </auto-generated>
#nullable enable

namespace RecursiveAI.OneHtml.Css;

internal static class NamedColorData
{
    /// <summary>Name and 0xRRGGBB value of every named colour, ordered by name.</summary>
    public static readonly (string Name, int Rgb)[] All =
    [
%s
    ];
}
""" % (date, hashlib.sha256(raw).hexdigest(), body)
    dest = os.path.join(ROOT, "src/OneHtml/Css/Generated/NamedColors.g.cs")
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("named colours", len(rows))


main()
