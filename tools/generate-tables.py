#!/usr/bin/env python3
"""Generates the committed lookup tables of RecursiveAI.OneHtml from the WHATWG data files.

Inputs (downloaded once; their SHA-256 is written into every generated file):
  encodings.json  https://encoding.spec.whatwg.org/encodings.json   (encoding names and labels)
  indexes.json    https://encoding.spec.whatwg.org/indexes.json     (legacy encoding indexes)
  entities.json   https://html.spec.whatwg.org/entities.json        (named character references)

Usage: tools/generate-tables.py <directory holding the three json files> [retrieval date]

Outputs (relative to the repository root):
  src/OneHtml/Encodings/Generated/EncodingTables.g.cs
  src/OneHtml/Encodings/Generated/EncodingLabels.g.cs
  src/OneHtml/Parsing/Generated/NamedCharacterReferences.g.cs

The files are deterministic: running the generator again on the same inputs changes nothing.
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NONE16 = 0xFFFF
NONE32 = 0xFFFFFFFF


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def array(name, values, ctype, none, doc):
    lines = []
    row = []
    for v in values:
        row.append(str(none if v is None else v))
        if len(row) == 16:
            lines.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    body = "\n".join(lines)
    return (f"    /// <summary>{doc}</summary>\n"
            f"    public static ReadOnlySpan<{ctype}> {name} => new {ctype}[]\n    {{\n{body}\n    }};\n")


def pascal(name):
    joined = "".join(t[:1].upper() + t[1:].lower() for t in re.split(r"[-_]", name))
    return re.sub(r"(?<=[0-9])([a-z])", lambda m: m.group(1).upper(), joined)


def main():
    src = sys.argv[1]
    date = sys.argv[2] if len(sys.argv) > 2 else "2026-10-25"
    enc_path = os.path.join(src, "encodings.json")
    idx_path = os.path.join(src, "indexes.json")
    ent_path = os.path.join(src, "entities.json")
    encodings = json.load(open(enc_path, encoding="utf-8"))
    indexes = json.load(open(idx_path, encoding="utf-8"))
    entities = json.load(open(ent_path, encoding="utf-8"))

    header = (
        "// <auto-generated>\n"
        "// Generated by tools/generate-tables.py. Do not edit by hand.\n"
        f"// Source data retrieved {date} from the WHATWG Encoding Standard (CC BY 4.0) and the WHATWG HTML Standard (CC BY 4.0):\n"
        f"//   https://encoding.spec.whatwg.org/encodings.json  sha256 {sha(enc_path)}\n"
        f"//   https://encoding.spec.whatwg.org/indexes.json    sha256 {sha(idx_path)}\n"
        f"//   https://html.spec.whatwg.org/entities.json       sha256 {sha(ent_path)}\n"
        "// </auto-generated>\n"
        "#nullable enable\n")

    # ---- indexes -----------------------------------------------------------------------------
    single_names = [k for k in indexes if k not in
                    ("big5", "euc-kr", "gb18030", "gb18030-ranges", "jis0208", "jis0212", "iso-2022-jp-katakana")]
    out = [header, "using System;\n\nnamespace RecursiveAI.OneHtml.Encodings;\n",
           "/// <summary>The Encoding Standard's indexes, as generated tables. A missing entry is 0xFFFF (0xFFFFFFFF for 32-bit tables).</summary>",
           "internal static class EncodingTables\n{"]
    out.append(f"    /// <summary>Marks a pointer with no code point in a 16-bit table.</summary>\n    public const ushort None16 = 0x{NONE16:04X};\n")
    out.append(f"    /// <summary>Marks a pointer with no code point in a 32-bit table.</summary>\n    public const uint None32 = 0x{NONE32:08X};\n")
    for key, prop in (("big5", "Big5"),):
        out.append(array(prop, indexes[key], "uint", NONE32, f"index {key}: pointer to code point."))
    for key, prop in (("euc-kr", "EucKr"), ("gb18030", "Gb18030"), ("jis0208", "Jis0208"), ("jis0212", "Jis0212")):
        assert max(v for v in indexes[key] if v is not None) < NONE16
        out.append(array(prop, indexes[key], "ushort", NONE16, f"index {key}: pointer to code point."))
    ranges = indexes["gb18030-ranges"]
    out.append(array("Gb18030RangePointers", [p for p, _ in ranges], "uint", NONE32, "index gb18030 ranges: first pointer of each range."))
    out.append(array("Gb18030RangeCodePoints", [c for _, c in ranges], "uint", NONE32, "index gb18030 ranges: code point of each range's first pointer."))
    for key in single_names:
        out.append(array("SingleByte_" + pascal(key.replace("iso-8859", "iso8859")), indexes[key], "ushort", NONE16,
                         f"index {key}: byte 0x80 + n to code point."))
    # Accessor by table id.
    out.append("    /// <summary>Returns the single-byte index with the given table id.</summary>\n"
               "    public static ReadOnlySpan<ushort> SingleByte(int id) => id switch\n    {")
    for i, key in enumerate(single_names):
        out.append(f"        {i} => SingleByte_{pascal(key.replace('iso-8859', 'iso8859'))},")
    out.append("        _ => throw new ArgumentOutOfRangeException(nameof(id)),\n    };\n}\n")
    write("src/OneHtml/Encodings/Generated/EncodingTables.g.cs", "\n".join(out))

    # ---- encodings and labels ---------------------------------------------------------------
    kind_by_name = {
        "UTF-8": "Utf8", "GBK": "Gbk", "gb18030": "Gb18030", "Big5": "Big5", "EUC-JP": "EucJp",
        "ISO-2022-JP": "Iso2022Jp", "Shift_JIS": "ShiftJis", "EUC-KR": "EucKr", "replacement": "Replacement",
        "UTF-16BE": "Utf16Be", "UTF-16LE": "Utf16Le", "x-user-defined": "XUserDefined",
    }
    flat = [e for g in encodings for e in g["encodings"]]
    out = [header, "using System;\nusing System.Collections.Generic;\n\nnamespace RecursiveAI.OneHtml.Encodings;\n",
           "public sealed partial class WhatwgEncoding\n{"]
    for e in flat:
        name = e["name"]
        if name in kind_by_name:
            kind, table = kind_by_name[name], -1
        else:
            kind = "SingleByte"
            key = "iso-8859-8" if name == "ISO-8859-8-I" else name.lower()
            table = single_names.index(key)
        out.append(f"    /// <summary>The Encoding Standard's <c>{name}</c> encoding.</summary>\n"
                   f"    public static WhatwgEncoding {pascal(name)} {{ get; }} = new(\"{name}\", EncodingKind.{kind}, {table});\n")
    out.append("    /// <summary>Every encoding in the Encoding Standard, in the standard's order.</summary>\n"
               "    public static IReadOnlyList<WhatwgEncoding> All { get; } = new WhatwgEncoding[]\n    {")
    for e in flat:
        out.append(f"        {pascal(e['name'])},")
    out.append("    };\n")
    out.append("    private static WhatwgEncoding? LookupLowerLabel(ReadOnlySpan<char> label)\n    {\n        switch (label)\n        {")
    for e in flat:
        for lab in e["labels"]:
            out.append(f"            case \"{lab}\": return {pascal(e['name'])};")
    out.append("            default: return null;\n        }\n    }\n}\n")
    write("src/OneHtml/Encodings/Generated/EncodingLabels.g.cs", "\n".join(out))

    # ---- named character references ----------------------------------------------------------
    names = sorted(k[1:] for k in entities)  # drop the leading '&'; ordinal order of UTF-16 code units
    assert names == sorted(names, key=lambda s: s.encode("utf-16-be"))
    chars = [entities["&" + n]["characters"] for n in names]
    values = [c.encode("utf-16-le").decode("utf-16-le") for c in chars]
    lens = [len(c.encode("utf-16-le")) // 2 for c in chars]
    assert max(lens) <= 4 and all("\n" not in n for n in names)
    namestr = "\n".join(names)
    valstr = "".join(values)

    def cs_escape(s):
        r = []
        for ch in s:
            o = ord(ch)
            if ch == "\\":
                r.append("\\\\")
            elif ch == '"':
                r.append('\\"')
            elif 0x20 <= o < 0x7F:
                r.append(ch)
            elif o >= 0x10000:
                v = o - 0x10000
                r.append("\\u%04X\\u%04X" % (0xD800 + (v >> 10), 0xDC00 + (v & 0x3FF)))
            else:
                r.append("\\u%04X" % o)
        return "".join(r)

    out = [header, "using System;\n\nnamespace RecursiveAI.OneHtml.Parsing;\n",
           "internal static partial class NamedCharacterReferences\n{",
           f"    /// <summary>Number of entries.</summary>\n    public const int Count = {len(names)};\n",
           f"    /// <summary>The longest name, including the semicolon when it has one.</summary>\n    public const int MaxNameLength = {max(len(n) for n in names)};\n",
           "    /// <summary>All names in ordinal order, without the leading ampersand and separated by line feeds.</summary>\n"
           f"    private const string NameData = \"{cs_escape(namestr)}\";\n",
           "    /// <summary>The replacement text of every entry, concatenated in the same order.</summary>\n"
           f"    private const string ValueData = \"{cs_escape(valstr)}\";\n",
           "    /// <summary>The length in UTF-16 code units of every entry's replacement text.</summary>\n"
           "    private static ReadOnlySpan<byte> ValueLengths => new byte[]\n    {"]
    row = []
    lines = []
    for n in lens:
        row.append(str(n))
        if len(row) == 32:
            lines.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    out.append("\n".join(lines))
    out.append("    };\n}\n")
    write("src/OneHtml/Parsing/Generated/NamedCharacterReferences.g.cs", "\n".join(out))


main()
