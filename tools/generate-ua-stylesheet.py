#!/usr/bin/env python3
"""Generates the user-agent stylesheet of RecursiveAI.OneHtml from the HTML Standard's Rendering section.

Input: https://html.spec.whatwg.org/multipage/rendering.html (saved as a file; its SHA-256 and the retrieval date
are written into the generated file). Every `<pre>` block of the section that is CSS is taken, except:
  - blocks the section introduces with "In quirks mode": they go into the quirks sheet;
  - the block after "ISO-8859-8" (the encoding-specific rules), and the examples that are HTML or script.

Usage: tools/generate-ua-stylesheet.py <rendering.html> <retrieval date yyyy-MM-dd>

Output: src/OneHtml/Css/Generated/UserAgentStylesheet.g.cs. Deterministic.
"""
import hashlib
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    path, date = sys.argv[1], sys.argv[2]
    raw = open(path, "rb").read()
    text = raw.decode("utf-8")
    standard, quirks = [], []
    for m in re.finditer(r"<pre>(.*?)</pre>", text, re.S):
        body = html.unescape(re.sub(r"<[^>]+>", "", m.group(1)))
        if not re.match(r"\s*(@namespace|[\w\[\]:*|.#, \n-]+\{)", body) or "alert(" in body or "<p " in body or "<table>" in body:
            continue
        before = html.unescape(re.sub(r"<[^>]+>", "", text[max(0, m.start() - 700):m.start()]))
        tail = " ".join(before.split())[-160:]
        if "ISO-8859-8" in tail:
            continue
        (quirks if "In quirks mode" in tail else standard).append(body.strip())

    def lit(blocks):
        ns = '@namespace "http://www.w3.org/1999/xhtml";'
        cleaned = [b.replace(ns, "").strip() for b in blocks]
        return ns + "\n\n" + "\n\n".join(cleaned) + "\n"

    out = []
    out.append("// <auto-generated>")
    out.append("// Generated by tools/generate-ua-stylesheet.py. Do not edit.")
    out.append("// Source: HTML Standard, section 15 \"Rendering\", https://html.spec.whatwg.org/multipage/rendering.html")
    out.append("//   retrieved " + date + ", SHA-256 " + hashlib.sha256(raw).hexdigest())
    out.append("// The CSS of the section is copyright WHATWG (CC BY 4.0; code portions BSD-3-Clause).")
    out.append("// </auto-generated>")
    out.append("namespace RecursiveAI.OneHtml.Css;")
    out.append("")
    out.append("internal static class UserAgentStylesheetData")
    out.append("{")
    out.append("    public const string SourceDate = \"" + date + "\";")
    out.append("")
    for name, blocks in (("Standard", standard), ("Quirks", quirks)):
        out.append("    public const string " + name + " = \"\"\"\"")
        out.append(lit(blocks).rstrip("\n"))
        out.append("\"\"\"\";")
        out.append("")
    out.append("}")
    dest = os.path.join(ROOT, "src", "OneHtml", "Css", "Generated", "UserAgentStylesheet.g.cs")
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(len(standard), "standard blocks,", len(quirks), "quirks blocks")


main()
